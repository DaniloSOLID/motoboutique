CREATE TABLE auditoria_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(120) NOT NULL,
    accion VARCHAR(80) NOT NULL,
    entidad VARCHAR(100) NOT NULL,
    entidad_id VARCHAR(80),
    detalle TEXT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
    creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    modificado_por VARCHAR(100),
    modificado_en TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_auditoria_fecha ON auditoria_eventos(fecha DESC);
CREATE INDEX idx_auditoria_actor_fecha ON auditoria_eventos(actor, fecha DESC);
CREATE INDEX idx_auditoria_entidad ON auditoria_eventos(entidad, entidad_id);

CREATE TABLE limite_recuperacion_password (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave VARCHAR(64) NOT NULL,
    intentos INTEGER NOT NULL DEFAULT 0,
    ventana_inicio TIMESTAMPTZ NOT NULL,
    bloqueado_hasta TIMESTAMPTZ,
    CONSTRAINT uq_limite_recuperacion_clave UNIQUE (clave)
);
CREATE INDEX idx_limite_recuperacion_ventana ON limite_recuperacion_password(ventana_inicio);

CREATE INDEX idx_conteos_fecha_estado ON conteos_fisicos(fecha_apertura DESC, estado);
CREATE INDEX idx_ajustes_almacen_fecha ON ajustes_inventario(almacen_id, fecha_solicitud DESC);
CREATE INDEX idx_ajustes_solicitante_fecha ON ajustes_inventario(solicitante_id, fecha_solicitud DESC);

ALTER TABLE auditoria_eventos ENABLE ROW LEVEL SECURITY;
ALTER TABLE limite_recuperacion_password ENABLE ROW LEVEL SECURITY;
