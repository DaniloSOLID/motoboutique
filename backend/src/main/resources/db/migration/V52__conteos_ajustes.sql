CREATE TABLE conteos_fisicos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero VARCHAR(30) NOT NULL,
 almacen_id BIGINT NOT NULL REFERENCES almacenes(id),
 estado VARCHAR(20) NOT NULL DEFAULT 'ABIERTO',
 fecha_apertura TIMESTAMPTZ NOT NULL DEFAULT now(), fecha_cierre TIMESTAMPTZ,
 responsable_id BIGINT REFERENCES usuarios(id),
 observaciones TEXT,
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_conteos_numero UNIQUE(numero), CONSTRAINT chk_conteos_estado CHECK(estado IN ('ABIERTO','CERRADO'))
);
CREATE TABLE conteo_detalles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conteo_id BIGINT NOT NULL REFERENCES conteos_fisicos(id), producto_id BIGINT NOT NULL REFERENCES productos(id),
 stock_sistema NUMERIC(14,3) NOT NULL CHECK(stock_sistema >= 0), stock_contado NUMERIC(14,3) NOT NULL CHECK(stock_contado >= 0), diferencia NUMERIC(14,3) NOT NULL,
 ajustado BOOLEAN NOT NULL DEFAULT FALSE,
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_conteo_producto UNIQUE(conteo_id,producto_id)
);
CREATE TABLE ajustes_inventario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero VARCHAR(30) NOT NULL,
 producto_id BIGINT NOT NULL REFERENCES productos(id), almacen_id BIGINT NOT NULL REFERENCES almacenes(id),
 cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad <> 0), motivo VARCHAR(255) NOT NULL,
 origen VARCHAR(20) NOT NULL DEFAULT 'MANUAL', estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
 solicitante_id BIGINT NOT NULL REFERENCES usuarios(id), aprobador_id BIGINT REFERENCES usuarios(id), comentario TEXT,
 fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT now(), fecha_resolucion TIMESTAMPTZ,
 conteo_detalle_id BIGINT REFERENCES conteo_detalles(id), movimiento_id BIGINT REFERENCES movimientos_inventario(id),
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_ajustes_numero UNIQUE(numero), CONSTRAINT chk_ajustes_origen CHECK(origen IN ('MANUAL','CONTEO')),
 CONSTRAINT chk_ajustes_estado CHECK(estado IN ('PENDIENTE','APROBADO','RECHAZADO'))
);
CREATE INDEX idx_conteos_almacen_estado ON conteos_fisicos(almacen_id, estado);
CREATE INDEX idx_conteo_detalles_producto ON conteo_detalles(producto_id);
CREATE INDEX idx_ajustes_estado_fecha ON ajustes_inventario(estado, fecha_solicitud DESC);
CREATE INDEX idx_ajustes_producto_almacen ON ajustes_inventario(producto_id, almacen_id);
