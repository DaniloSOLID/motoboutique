-- ============================================================
-- V2: Seguridad (usuarios, roles, permisos y recuperación de contraseña)
-- ============================================================
-- Las tablas de entidades incluyen las columnas de AuditableEntity:
--   id, creado_por, creado_en, modificado_por, modificado_en, version, eliminado

-- ------------------------------------------------------------
-- Permisos (granulares, ej. PRODUCTO_EDITAR). Se cargan desde el DataSeeder.
-- ------------------------------------------------------------
CREATE TABLE permisos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(60)  NOT NULL,
    descripcion    VARCHAR(200) NOT NULL,
    modulo         VARCHAR(40)  NOT NULL,
    creado_por     VARCHAR(100) NOT NULL DEFAULT 'sistema',
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    modificado_por VARCHAR(100),
    modificado_en  TIMESTAMPTZ,
    version        BIGINT       NOT NULL DEFAULT 0,
    eliminado      BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_permisos_codigo UNIQUE (codigo)
);

-- ------------------------------------------------------------
-- Roles. "sistema" marca los roles base, que no se pueden borrar.
-- ------------------------------------------------------------
CREATE TABLE roles (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(40)  NOT NULL,
    nombre         VARCHAR(80)  NOT NULL,
    descripcion    VARCHAR(200),
    sistema        BOOLEAN      NOT NULL DEFAULT FALSE,
    creado_por     VARCHAR(100) NOT NULL DEFAULT 'sistema',
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    modificado_por VARCHAR(100),
    modificado_en  TIMESTAMPTZ,
    version        BIGINT       NOT NULL DEFAULT 0,
    eliminado      BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_roles_codigo UNIQUE (codigo)
);

-- ------------------------------------------------------------
-- Usuarios. La contraseña se guarda con BCrypt (60 caracteres).
-- ------------------------------------------------------------
CREATE TABLE usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(120) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    password       VARCHAR(100) NOT NULL,
    telefono       VARCHAR(20),
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_por     VARCHAR(100) NOT NULL DEFAULT 'sistema',
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    modificado_por VARCHAR(100),
    modificado_en  TIMESTAMPTZ,
    version        BIGINT       NOT NULL DEFAULT 0,
    eliminado      BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Correo único sin distinguir mayúsculas de minúsculas
CREATE UNIQUE INDEX uq_usuarios_email ON usuarios (lower(email));

-- ------------------------------------------------------------
-- Relaciones muchos-a-muchos
-- ------------------------------------------------------------
CREATE TABLE usuarios_roles (
    usuario_id BIGINT NOT NULL,
    rol_id     BIGINT NOT NULL,
    CONSTRAINT pk_usuarios_roles PRIMARY KEY (usuario_id, rol_id),
    CONSTRAINT fk_usuarios_roles_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_usuarios_roles_rol FOREIGN KEY (rol_id) REFERENCES roles (id)
);
CREATE INDEX idx_usuarios_roles_rol ON usuarios_roles (rol_id);

CREATE TABLE roles_permisos (
    rol_id     BIGINT NOT NULL,
    permiso_id BIGINT NOT NULL,
    CONSTRAINT pk_roles_permisos PRIMARY KEY (rol_id, permiso_id),
    CONSTRAINT fk_roles_permisos_rol FOREIGN KEY (rol_id) REFERENCES roles (id),
    CONSTRAINT fk_roles_permisos_permiso FOREIGN KEY (permiso_id) REFERENCES permisos (id)
);
CREATE INDEX idx_roles_permisos_permiso ON roles_permisos (permiso_id);

-- ------------------------------------------------------------
-- Tokens de recuperación de contraseña.
-- Se guarda el HASH (SHA-256 en hexadecimal) del token, nunca el token en claro.
-- ------------------------------------------------------------
CREATE TABLE tokens_recuperacion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT       NOT NULL,
    token_hash     VARCHAR(64)  NOT NULL,
    expira_en      TIMESTAMPTZ  NOT NULL,
    usado_en       TIMESTAMPTZ,
    creado_por     VARCHAR(100) NOT NULL DEFAULT 'sistema',
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    modificado_por VARCHAR(100),
    modificado_en  TIMESTAMPTZ,
    version        BIGINT       NOT NULL DEFAULT 0,
    eliminado      BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_tokens_recuperacion_hash UNIQUE (token_hash),
    CONSTRAINT fk_tokens_recuperacion_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);
CREATE INDEX idx_tokens_recuperacion_usuario ON tokens_recuperacion (usuario_id);