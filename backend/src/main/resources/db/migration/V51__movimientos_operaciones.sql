CREATE TABLE transferencias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero VARCHAR(30) NOT NULL,
 almacen_origen_id BIGINT NOT NULL REFERENCES almacenes(id),
 almacen_destino_id BIGINT NOT NULL REFERENCES almacenes(id),
 estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
 fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 observaciones TEXT,
 solicitante_id BIGINT REFERENCES usuarios(id),
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_transferencias_numero UNIQUE(numero),
 CONSTRAINT chk_transferencias_estado CHECK(estado IN ('PENDIENTE','EN_TRANSITO','COMPLETADA','CANCELADA')),
 CONSTRAINT chk_transferencias_almacenes CHECK(almacen_origen_id <> almacen_destino_id)
);
CREATE TABLE transferencia_detalles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 transferencia_id BIGINT NOT NULL REFERENCES transferencias(id),
 producto_id BIGINT NOT NULL REFERENCES productos(id),
 cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad > 0),
 movimiento_salida_id BIGINT REFERENCES movimientos_inventario(id),
 movimiento_entrada_id BIGINT REFERENCES movimientos_inventario(id),
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_transferencia_producto UNIQUE(transferencia_id, producto_id)
);
CREATE INDEX idx_transferencias_estado_fecha ON transferencias(estado, fecha DESC);
CREATE INDEX idx_transferencias_origen ON transferencias(almacen_origen_id);
CREATE INDEX idx_transferencia_detalles_producto ON transferencia_detalles(producto_id);

ALTER TABLE movimientos_inventario DROP CONSTRAINT IF EXISTS chk_movimientos_tipo;
ALTER TABLE movimientos_inventario ADD CONSTRAINT chk_movimientos_tipo CHECK(tipo IN ('ENTRADA','SALIDA','TRANSFERENCIA_SALIDA','TRANSFERENCIA_ENTRADA','AJUSTE_POSITIVO','AJUSTE_NEGATIVO','RECEPCION'));
CREATE INDEX IF NOT EXISTS idx_movimientos_tipo_fecha ON movimientos_inventario(tipo, fecha DESC);
