CREATE TABLE configuracion_empresa (
 id SMALLINT PRIMARY KEY DEFAULT 1 CHECK(id = 1), razon_social VARCHAR(180), ruc VARCHAR(11), moneda VARCHAR(3) NOT NULL DEFAULT 'PEN',
 igv NUMERIC(5,2) NOT NULL DEFAULT 18.00 CHECK(igv >= 0), almacen_defecto_id BIGINT REFERENCES almacenes(id), stock_minimo_default NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(stock_minimo_default >= 0),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
