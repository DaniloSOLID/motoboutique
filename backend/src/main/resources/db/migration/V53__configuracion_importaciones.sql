CREATE TABLE importaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, archivo VARCHAR(255) NOT NULL, fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 filas_validas INTEGER NOT NULL DEFAULT 0 CHECK(filas_validas >= 0), errores INTEGER NOT NULL DEFAULT 0 CHECK(errores >= 0),
 estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE', usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT chk_importaciones_estado CHECK(estado IN ('PENDIENTE','PROCESANDO','COMPLETADA','PARCIAL','ERROR'))
);
CREATE TABLE importacion_errores (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, importacion_id BIGINT NOT NULL REFERENCES importaciones(id) ON DELETE CASCADE,
 fila INTEGER NOT NULL CHECK(fila > 0), columna VARCHAR(80), mensaje TEXT NOT NULL
);
CREATE INDEX idx_importaciones_fecha ON importaciones(fecha DESC);
CREATE INDEX idx_importaciones_estado ON importaciones(estado);
CREATE INDEX idx_importacion_errores_importacion ON importacion_errores(importacion_id);
