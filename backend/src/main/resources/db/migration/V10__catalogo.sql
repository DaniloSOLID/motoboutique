CREATE TABLE categorias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(100) NOT NULL, descripcion VARCHAR(255), activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ, version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_categorias_nombre UNIQUE (nombre)
);
CREATE TABLE marcas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(100) NOT NULL, descripcion VARCHAR(255), activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ, version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_marcas_nombre UNIQUE (nombre)
);
CREATE TABLE modelos_moto (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, marca_id BIGINT NOT NULL REFERENCES marcas(id), nombre VARCHAR(120) NOT NULL, anio_inicio INTEGER, anio_fin INTEGER,
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ, version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_modelos_moto UNIQUE (marca_id,nombre)
);
CREATE TABLE productos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, categoria_id BIGINT NOT NULL REFERENCES categorias(id), marca_id BIGINT REFERENCES marcas(id), codigo VARCHAR(60) NOT NULL, nombre VARCHAR(180) NOT NULL, descripcion TEXT, precio_compra NUMERIC(14,2) NOT NULL CHECK(precio_compra >= 0), precio_venta NUMERIC(14,2) NOT NULL CHECK(precio_venta >= 0), stock_minimo NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(stock_minimo >= 0), unidad VARCHAR(20) NOT NULL DEFAULT 'UNIDAD', activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_por VARCHAR(100) NOT NULL DEFAULT 'sistema', creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), modificado_por VARCHAR(100), modificado_en TIMESTAMPTZ, version BIGINT NOT NULL DEFAULT 0, eliminado BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT uq_productos_codigo UNIQUE (codigo)
);
CREATE TABLE producto_compatibilidades (
 producto_id BIGINT NOT NULL REFERENCES productos(id), modelo_moto_id BIGINT NOT NULL REFERENCES modelos_moto(id), PRIMARY KEY(producto_id,modelo_moto_id)
);
CREATE INDEX idx_modelos_marca ON modelos_moto(marca_id);
CREATE INDEX idx_productos_categoria ON productos(categoria_id);
CREATE INDEX idx_productos_nombre_trgm ON productos USING GIN(nombre gin_trgm_ops);
